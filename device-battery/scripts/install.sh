#!/usr/bin/env bash
# Install the device-battery helper, its udev rule, and the Plasma applet.
set -euo pipefail

widget_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
bin_dir="${HOME}/.local/bin"
helper="${bin_dir}/device-battery"
# The helper runs from a copy, so switching branches never changes the installed widget.
lib_dir="${XDG_DATA_HOME:-${HOME}/.local/share}/device-battery-widget"
applet_id="com.nicl9923.devicebattery"
rule_name="70-device-battery.rules"

command -v kpackagetool6 >/dev/null || { echo "kpackagetool6 not found (install plasma-workspace)" >&2; exit 1; }

echo "==> Installing helper to ${helper}"
mkdir -p "$bin_dir" "$lib_dir"
staged="$(mktemp -d "${lib_dir}/.device_battery.XXXXXX")"
cp -r "${widget_root}/src/device_battery/." "$staged"
rm -rf "${staged}/__pycache__" "${lib_dir}/device_battery"
mv "$staged" "${lib_dir}/device_battery"
revision="$(git -C "$widget_root" describe --always --dirty 2>/dev/null || echo unknown)"
cat > "$helper" <<SCRIPT
#!/usr/bin/env bash
# Generated by widgets/device-battery/scripts/install.sh from revision ${revision}
exec env PYTHONPATH="${lib_dir}\${PYTHONPATH:+:\$PYTHONPATH}" python3 -m device_battery "\$@"
SCRIPT
chmod +x "$helper"

# Razer dongles need a udev rule before the logged-in user can open their hidraw node.
if ! cmp -s "${widget_root}/udev/${rule_name}" "/etc/udev/rules.d/${rule_name}"; then
  echo "==> Installing udev rule (needs sudo)"
  sudo install -m 644 "${widget_root}/udev/${rule_name}" "/etc/udev/rules.d/${rule_name}"
  sudo udevadm control --reload
  sudo udevadm trigger --action=change --subsystem-match=hidraw
fi
if ! command -v headsetcontrol >/dev/null; then
  echo "    HeadsetControl is not installed. Wireless gaming headsets need it:"
  echo "      sudo dnf install headsetcontrol   # Fedora"
fi

echo "==> Checking helper"
"$helper" --plain

echo "==> Installing plasmoid"
if kpackagetool6 -t Plasma/Applet -l 2>/dev/null | grep -qx "$applet_id"; then
  kpackagetool6 -t Plasma/Applet -u "${widget_root}/plasmoid"
else
  kpackagetool6 -t Plasma/Applet -i "${widget_root}/plasmoid"
fi
echo "Add it from: right-click the panel > Add Widgets > Device Battery"
